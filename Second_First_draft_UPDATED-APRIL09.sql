CREATE TABLE VISIT
(V_ID CHAR(3) PRIMARY KEY,
V_DATE DATE,
DIAGNOSIS VARCHAR(250),
T_ID CHAR(5) FOREIGN KEY REFERENCES TREATMENT,
AP_ID CHAR(5) FOREIGN KEY REFERENCES APPOINTMENT);


CREATE TABLE APPOINTMENT
(AP_ID CHAR(5) PRIMARY KEY,
D_ID CHAR(3) FOREIGN KEY REFERENCES DENTIST,
P_ID INT FOREIGN KEY REFERENCES PATIENT,
AP_DATE DATE,
AP_TIME TIME,
REASON VARCHAR(40),
STATUS BIT --1 = SCHEDULED, 0 = UNSCHEDULED
);
