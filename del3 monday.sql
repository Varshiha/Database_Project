--function procedure
CREATE FUNCTION ANNUAL_PATIENTS (@DENTIST_ID CHAR(3)) 
RETURNS INT 
AS
BEGIN 
DECLARE @NUM_PATIENTS INT; 
	IF NOT EXISTS (SELECT 1 FROM DENTIST WHERE D_ID = @DENTIST_ID) 
		RETURN 0; 
	ELSE 
		BEGIN 
			SET @NUM_PATIENTS = (SELECT COUNT(P_ID) FROM APPOINTMENT WHERE D_ID = @DENTIST_ID AND YEAR(AP_DATE) = YEAR(GETDATE())); 
		END 
	RETURN @NUM_PATIENTS; 
END; 
--procedure
CREATE PROCEDURE DENTIST_ANNUAL_SALARY (@DENTIST_ID CHAR(3)) 
AS 
BEGIN 
BEGIN TRY 
DECLARE @COMMISSION NUMERIC (5,2),@PAY MONEY, @NUM_PATIENTS INT; 
IF NOT EXISTS (SELECT 1 FROM DENTIST WHERE D_ID = @DENTIST_ID) 
	PRINT 'This dentist does not exist.' 
ELSE IF NOT EXISTS (SELECT 1 FROM APPOINTMENT WHERE D_ID = @DENTIST_ID AND YEAR(AP_DATE) = YEAR(GETDATE())) 
	BEGIN
		SET @PAY = 0; 
		PRINT 'The dentist ' + @DENTIST_ID + ' did not see any patients this year.' 
	END 
ELSE 
	BEGIN 
		SELECT @PAY = (SELECT SUM(T_COST)  
		FROM TREATMENT T JOIN VISIT V 
		ON T.T_ID = V.T_ID 
		JOIN APPOINTMENT A 
		ON A.AP_ID = V.AP_ID 
		WHERE A.D_ID = @DENTIST_ID AND YEAR(A.AP_DATE) = YEAR(GETDATE()));
		SELECT @NUM_PATIENTS = DBO.ANNUAL_PATIENTS(@DENTIST_ID); 
		SELECT @COMMISSION = CASE 
			WHEN @NUM_PATIENTS < 2 THEN 0 
			ELSE 0.15 
			END; 
		SET @PAY = @PAY + (@COMMISSION*@PAY); 
		PRINT 'The dentist ' + @DENTIST_ID + ' has an annual pay of $' + CAST(@PAY AS VARCHAR(7)) + '.'; 
	END 
END TRY 
BEGIN CATCH 
THROW 
END CATCH 
END; 

