SELECT P.P_ID, P.P_Fname, P.P_Lname, SUM(B.B_Total_Amount) AS Total_Billed, SUM(COALESCE(PA.Total_Paid,0)) AS Total_Paid, (SUM(B.B_Total_Amount) - SUM(COALESCE(PA.Total_Paid,0))) AS Remaining_Balance
FROM PATIENT P JOIN APPOINTMENT A
ON P.P_ID = A.P_ID
JOIN VISIT V 
ON A.AP_ID = V.AP_ID
JOIN BILL B
ON B.V_ID = V.V_ID
LEFT JOIN (SELECT B_ID, SUM(PAY_Amount) AS Total_Paid
            FROM PAYMENT
            GROUP BY B_ID) PA
ON PA.B_ID = B.B_ID
GROUP BY P.P_ID, P.P_Fname, P.P_Lname
ORDER BY Remaining_Balance DESC;
