CREATE TRIGGER TRG_BILL_PATIENT_BALANCE
ON BILL
AFTER INSERT
AS
DECLARE @ERRORMESSAGE VARCHAR(200) = 'Tigger error';
BEGIN
BEGIN TRY
IF EXISTS(SELECT 1 FROM INSERTED WHERE B_TOTAL_AMOUNT IS NULL OR B_TOTAL_AMOUNT <= 0)
   BEGIN
    SET @ERRORMESSAGE = 'Bill amount cannot be null or negative or 0'
    RAISERROR(@ERRORMESSAGE, 16,1)
    ROLLBACK TRANSACTION;
   END
ELSE IF NOT EXISTS(SELECT 1 FROM PATIENT P JOIN APPOINTMENT A ON P.P_ID = A.P_ID
									       JOIN VISIT V ON A.AP_ID = V.AP_ID
									       JOIN INSERTED I ON I.V_ID = V.V_ID)                  
   BEGIN
    SET @ERRORMESSAGE = 'Patient does not exist.'
    RAISERROR(@ERRORMESSAGE, 16,1)
    ROLLBACK TRANSACTION;
   END;
ELSE 
   BEGIN
   UPDATE P 
   SET P.PAT_BALANCE = P.PAT_BALANCE + I.B_TOTAL_AMOUNT
   FROM PATIENT P JOIN APPOINTMENT A ON P.P_ID = A.P_ID JOIN VISIT V ON A.AP_ID = V.AP_ID
									  JOIN INSERTED I ON I.V_ID = V.V_ID;
   END;
END TRY
BEGIN CATCH
 RAISERROR(@ERRORMESSAGE, 16,1)
 ROLLBACK TRANSACTION 
END CATCH;

END;
GO
