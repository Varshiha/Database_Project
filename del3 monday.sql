CREATE PROCEDURE PRC_ADD_PAYMENT @B_ID CHAR(5), @P_ID CHAR(5), @PAY_AMOUNT DECIMAL(10,2), @PAY_METHOD VARCHAR(300)
AS
BEGIN
 BEGIN TRY
   IF @PAY_AMOUNT<= 0
       BEGIN
          RAISERROR('Amount cannot be 0 or less', 16,1);
       END;
   ELSE IF NOT EXISTS (SELECT 1 FROM PATIENT WHERE P_ID = @P_ID)
       BEGIN
          RAISERROR('Patient does not exist', 16,1)
       END;
   ELSE IF NOT EXISTS (SELECT 1 FROM BILL B JOIN VISIT V ON B.V_ID = V.V_ID JOIN APPOINTMENT A ON A.AP_ID = V.AP_ID JOIN PATIENT P ON A.P_ID = P.P_ID WHERE B.B_ID = @B_ID)
       BEGIN
          RAISERROR('Bill does not exist', 16,1)
       END;
   ELSE IF @PAY_METHOD NOT IN ('CASH', 'CARD', 'INSURANCE')
       BEGIN
       RAISERROR ('Pay method must be CASH, CARD OR INSURANCE', 16, 1)
       END;
   ELSE 
       BEGIN
          INSERT INTO PAYMENT(PAY_ID,PAY_Date, PAY_Method,PAY_Amount, P_ID, B_ID) 
          VALUES(NEXT VALUE FOR SEQ_PAYMENT, GETDATE(), @PAY_METHOD, @PAY_AMOUNT, @P_ID, @B_ID); 
          DECLARE @REMAINING DECIMAL(10,2)
          SET @REMAINING = DBO.FUNC_REMAINNING_BALANCE(@B_ID)
          IF @REMAINING <= 0
             BEGIN
                UPDATE BILL
                SET B_PAID_STATUS = 'PAID'
                WHERE B_ID = @B_ID;
             END;
          ELSE IF @REMAINING < (SELECT B_TOTAL_AMOUNT FROM BILL WHERE B_ID = @B_ID)
             BEGIN
                UPDATE BILL
                SET B_PAID_STATUS = 'PARTIAL'
                WHERE B_ID = @B_ID;
             END;
       END;
  END TRY
  BEGIN CATCH
      THROW;
  END CATCH;
END;
GO
