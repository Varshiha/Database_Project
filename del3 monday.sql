CREATE FUNCTION FUNC_REMAINNING_BALANCE (@B_ID CHAR(5))
RETURNS DECIMAL(10,2)
AS
BEGIN
    DECLARE @REMAININGBALANCE DECIMAL(10,2), @TOTAL DECIMAL(10,2), @PAID DECIMAL(10,2)

    --GET THE BILL
    SELECT @TOTAL = B_TOTAL_AMOUNT FROM BILL WHERE B_ID = @B_ID;
    --GET THE PAYMENT
     SELECT @PAID = SUM(PAY_AMOUNT) FROM PAYMENT WHERE B_ID = @B_ID;
     IF(@PAID IS NULL) 
        BEGIN
        SET @PAID = 0;
        END;
     SET @REMAININGBALANCE = @TOTAL-@PAID;
     RETURN @REMAININGBALANCE;
END;
GO

